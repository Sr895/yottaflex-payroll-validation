"""Export only approved payroll inputs to CSV and JSON."""
import json
import pandas as pd
from .config import DATA_PROCESSED, REPORTS

def export_approved():
    payroll = pd.read_csv(DATA_PROCESSED / "payroll_inputs.csv")
    approved = payroll[payroll.approval_status == "APPROVED"].copy()
    columns = ["payroll_input_id", "employee_id", "pay_period_id",
               "regular_hours", "allowance_total", "deduction_total",
               "gross_pay", "net_pay"]
    csv_path = REPORTS / "approved_payroll_export.csv"
    json_path = REPORTS / "approved_payroll_export.json"
    approved[columns].to_csv(csv_path, index=False)
    approved[columns].to_json(json_path, orient="records", indent=2)
    return {"approved_records": len(approved), "csv": str(csv_path), "json": str(json_path)}

def export_sql_insert():
    payroll = pd.read_csv(DATA_PROCESSED / "payroll_inputs.csv")
    approved = payroll[payroll.approval_status == "APPROVED"]
    path = REPORTS / "approved_payroll_export.sql"
    with path.open("w", encoding="utf-8") as f:
        f.write("-- Approved payroll export generated by Yottaflex demo\\n")
        f.write("BEGIN;\\n")
        for r in approved.itertuples():
            f.write(
                "INSERT INTO payroll_export_staging "
                "(payroll_input_id, employee_id, pay_period_id, net_pay) VALUES "
                f"('{r.payroll_input_id}', '{r.employee_id}', '{r.pay_period_id}', {r.net_pay:.2f});\\n"
            )
        f.write("COMMIT;\\n")
    return str(path)
